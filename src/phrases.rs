pub fn pick(previous: Option<usize>) -> usize {
    loop {
        let i = rand::random_range(0..TEXTS.len());
        if Some(i) != previous {
            return i;
        }
    }
}

#[cfg(test)]
mod tests {
    use super::TEXTS;

    #[test]
    fn texts_are_unique_and_balanced() {
        let unique: std::collections::HashSet<_> = TEXTS.iter().collect();
        assert_eq!(unique.len(), TEXTS.len());
        for t in TEXTS {
            assert!((90..=150).contains(&t.len()), "{} : {t}", t.len());
            assert!(!t.contains("  ") && t.trim() == *t, "{t}");
        }
    }
}
